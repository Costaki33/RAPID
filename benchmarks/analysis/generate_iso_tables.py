def canonical_core_budget_data():
    C = {}
    for p in glob.glob(str(FULL / "native" / "**" / "result.json"), recursive=True):
        r = jload(p)
        if not r:
            continue
        m = r["meta"]; method = m.get("method"); device = m.get("device")
        cores = m.get("n_cpus"); tag = str(m.get("tag", ""))
        if (method not in {"classify", "classify_batched", "annotate", "slipstream"}
                or device not in {"cpu", "gpu"} or cores not in {5, 10, 15, 20}
                or str(m.get("dataset", "")).lower() != "stead"
                or m.get("n_stations") != 580 or m.get("torch_threads") != 1
                or m.get("dtype") not in (None, "fp32") or bool(m.get("compile"))):
            continue
        expected = f"{'gpu_' if device == 'gpu' else ''}c{cores}_thr1"
        if method == "slipstream":
            expected += "_fp32"
        if tag != expected:
            continue
        total = (r.get("timing") or {}).get("total_s_mean")
        if total is not None:
            C.setdefault((method, m["model"], device), {})[cores] = total
    return C


def fig_core_budget():
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    C = canonical_core_budget_data()
    meths = ["classify", "classify_batched", "annotate", "slipstream"]
    titles = ["Per-Station Classify", "Network-Batched Classify", "Annotate", "Slipstream-FP32"]
    colors = {"PhaseNet": "#2e86c1", "PhaseNetLight": "#27ae60",
              "EQTransformer": "#e67e22", "EQT-NC": "#c0392b"}
    fig, axes = plt.subplots(1, 4, figsize=(15, 4.3), sharex=True)
    for ax, meth, title in zip(axes, meths, titles):
        for mo in MODELS:
            for device, ls, marker in (("cpu", "-", "o"), ("gpu", "--", "s")):
                d = C.get((meth, mo, device), {})
                if d:
                    xs = sorted(d)
                    ax.plot(xs, [d[x] for x in xs], marker=marker, ls=ls,
                            label=f"{mo} ({device.upper()})", color=colors[mo])
        ax.axhline(10, color="k", ls=":", lw=1)
        ax.set_xticks([5, 10, 15, 20]); ax.set_xlabel("host CPU-core allocation")
        ax.set_title(title); ax.grid(alpha=0.3)
    axes[0].set_ylabel("total runtime (s)")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=4, fontsize=7)
    fig.suptitle("Single-process host-core budget at one PyTorch intra-op thread — STEAD 580 stations",
                 fontsize=10)
    fig.tight_layout(rect=(0, 0.14, 1, 0.94))
    fig.savefig(OUT / "fig_core_budget.png", bbox_inches="tight"); plt.close(fig)


